HEAD = """# {title}
# Generated by gen_robotwin.py. Expert check skipped: seeds 100000+ in order (some may be unsolvable, fine for timing).
server:
  url: "ws://localhost:8000"
docker:
  image: ghcr.io/allenai/vla-evaluation-harness/robotwin:0.7.0
render: gpu
output_dir: "./results"
benchmarks:
"""


def entry(task: str, cfg: str, n: int) -> str:
    return (
        f'  - benchmark: "vla_eval.benchmarks.robotwin.benchmark:RoboTwinBenchmark"\n'
        f"    subname: {task}-{cfg}\n    episodes_per_task: 1\n    max_steps: {STEP_LIM[task]}\n    action_dim: 14\n"
        f"    params: {{task_name: {task}, task_config: {cfg}, seed: 0, instruction_type: seen, test_num: {n}, "
        f"skip_expert_check: true}}\n"
    )


def write(name: str, title: str, tasks: list[str], cfgs: list[str], n: int) -> None:
    Path(__file__).with_name(name).write_text(
        HEAD.format(title=title) + "".join(entry(t, c, n) for c in cfgs for t in tasks)
    )


