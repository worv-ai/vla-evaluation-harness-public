"""Single source of image capabilities and runtime layout."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
CATALOG = json.loads((ROOT / "images.json").read_text())
BENCHMARKS = CATALOG["benchmarks"]


def shell_catalog():
    import shlex

    groups = {
        "BASE_IMAGES": CATALOG["bases"],
        "BENCHMARKS": [n for n, s in BENCHMARKS.items() if "parent" not in s],
        "DERIVED_BENCHMARKS": [n for n, s in BENCHMARKS.items() if "parent" in s],
        "CPU_BENCHMARKS": [n for n, s in BENCHMARKS.items() if s["cpu"]],
        "SPLIT_BENCHMARKS": [n for n, s in BENCHMARKS.items() if "split" in s["layouts"]],
        "NO_REDIST": [n for n, s in BENCHMARKS.items() if not s["redistributable"]],
    }
    return (
        "# Generated by docker/render.py; edit docker/images.json.\n"
        + "\n".join(name + "=(" + " ".join(shlex.quote(v) for v in values) + ")" for name, values in groups.items())
        + "\n"
        + "".join(
            "declare -A "
            + variable
            + "=(\n"
            + "\n".join(
                "  [" + name + "]=" + shlex.quote(spec[key])
                for name, spec in BENCHMARKS.items()
                if "runtime_paths" in spec
            )
            + "\n)\n"
            for variable, key in (("BUILDERS", "builder"), ("GPU_RUNTIMES", "gpu_runtime"))
        )
        + "declare -A EULA_GATED=(\n"
        + "\n".join(
            "  [" + n + "]=" + shlex.quote(s["license"]["argument"] + " " + s["license"]["url"])
            for n, s in BENCHMARKS.items()
            if "license" in s
        )
        + "\n)\n"
    )
