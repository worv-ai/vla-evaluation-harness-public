"""Render checked-in Dockerfiles from explicit benchmark recipes and runtime layouts."""

import argparse

from catalog import BENCHMARKS, ROOT, shell_catalog


def render(name, spec):
    recipe = (ROOT / "recipes" / (name + ".Dockerfile")).read_text().rstrip()
    sources = ["FROM ${BASE_IMAGE} AS sources"]
    for source in spec.get("sources", []):
        arg = source["revision_arg"]
        sources += [
            f"ARG {arg}={source['revision']}",
            f"RUN mkdir -p {source['path']} && cd {source['path']} && git init -q "
            f'&& git remote add origin {source["url"]} && git fetch -q --depth 1 origin "${{{arg}}}" '
            "&& git checkout -q FETCH_HEAD "
            + ("&& git submodule update --init --recursive --depth 1 " if source["submodules"] else "")
            + "&& { git remote get-url origin; git rev-parse HEAD; } >> /usr/local/share/vla-build/sources.txt",
        ]
    if spec.get("sources"):
        recipe = recipe.replace(
            "FROM ${BASE_IMAGE} AS builder",
            "\n".join(sources) + "\nFROM ${BASE_IMAGE} AS builder",
            1,
        )
    if spec.get("sources"):
        offset = recipe.index("COPY --from=sources")
        recipe = (
            recipe[:offset]
            + "COPY --from=sources /usr/local/share/vla-build/sources.txt /usr/local/share/vla-build/sources.txt\n"
            + recipe[offset:]
        )
    # Instructions, including native runtime packages, are explicit catalog data.
    runtime = spec["runtime_instructions"]
    split = next(i for i, line in enumerate(runtime) if line.startswith("RUN dpkg-query"))
    before, after = runtime[:split], runtime[split:]
    paths = [*spec["runtime_paths"], "/usr/local/share/vla-build"]
    output = ["# Generated by docker/render.py; edit docker/recipes and docker/images.json.", recipe]
    output += [
        "COPY docker/images.json /usr/local/lib/vla/images.json",
        "ARG IMAGE_PROFILE=gpu",
        f"COPY docker/locks/{name}-${{IMAGE_PROFILE}}.txt /usr/local/lib/vla/locks/{name}-${{IMAGE_PROFILE}}.txt",
        "COPY docker/locks/assets.json /usr/local/lib/vla/locks/assets.json",
        "RUN mkdir -p /app /root",
        f'RUN python /usr/local/lib/vla/install_locked.py {name} "$IMAGE_PROFILE"',
    ]
    if spec["cpu"]:
        commands = []
        if spec["prune"]["libero_numpy"]:
            commands.append("python /usr/local/lib/vla/optimize_libero.py")
        commands += ["python /usr/local/lib/vla/prepare_cpu.py", "python /usr/local/lib/vla/prune_cpu.py"]
        output += ['RUN if [ "$IMAGE_PROFILE" = cpu ]; then ' + " && ".join(commands) + "; fi"]
    output += ["RUN python /usr/local/lib/vla/export_runtime.py --inventory-only " + " ".join(spec["runtime_paths"])]
    output += ["FROM builder AS assembled", "RUN python /usr/local/lib/vla/assemble.py " + name]
    output += ["FROM scratch AS assets"]
    output += [f"COPY --from=assembled {path} {path}" for path in spec["assets"]]
    output += [
        "COPY --from=assembled /runtime-root/usr/local/share/vla-build/assets.json /usr/local/share/vla-build/assets.json"
    ]
    output += ["FROM ${RUNTIME_IMAGE} AS runtime", *before]
    output += [f"COPY --from=assembled /runtime-root{path} {path}" for path in paths]
    output += after
    output += ["FROM runtime AS full"]
    output += [f"COPY --from=assets {path} {path}" for path in spec["assets"]]
    return "\n".join(output) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = {ROOT / "images.sh": shell_catalog()}
    for name, spec in BENCHMARKS.items():
        if "runtime_paths" in spec:
            outputs[ROOT / ("Dockerfile." + name)] = render(name, spec)
    stale = []
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT.parent)))
        else:
            path.write_text(content)
    if stale:
        parser.exit(1, "Generated files are stale: " + ", ".join(stale) + "\n")


if __name__ == "__main__":
    main()
